class StubArchitect:
    """Детерминированная библия-шаблон: культ, жрущий город. Валидна по правилам §3."""

    def build(self, seed: str, city: str, rng=None) -> dict:
        rng = rng or random.Random(f"plot|{city}|{seed}")
        cast, cid = [], 0

        def add(cat, role, imp, want, chekhov, rank=None, boss=None):
            nonlocal cid
            cid += 1
            a = {"id": f"cast:{cid}", "категория": cat, "роль": role, "важность": imp,
                 "желание": want, "секрет": f"скрывает: {want} (гейт: доверие/улика)",
                 "арка": None, "актёр": None, "чехов": chekhov, "память": None}
            if rank:
                a["иерархия"] = {"структура": "культ", "ранг": rank,
                                 "подчиняется": boss}
            cast.append(a)
            return a

        boss_of = {}
        for rank, role, imp, want, chek in _ENEMY_TPL:
            a = add("враг", role, imp, want, chek, rank=rank,
                    boss=boss_of.get(rank - 1))
            boss_of.setdefault(rank, a["id"])
        for role, imp, want, chek in _ALLY_TPL:
            add("союзник", role, imp, want, chek)
        for role, imp, want, chek in _NEUTRAL_TPL:
            add("нейтрал", role, imp, want, chek)
        # арки: слабое звено (перевербовка игроком) и правая рука (падение)
        next(a for a in cast if a["роль"] == "слабое звено")["арка"] = \
            "перевербовка: доверие/шантаж → сдаёт бухгалтерию"
        next(a for a in cast if a["роль"] == "правая рука")["арка"] = \
            "падение: подсидев фасада, приводит культ к краху"
        # смутные лица из прошлого (НЕ антагонист — правда добывается заново)
        next(a for a in cast if a["роль"] == "фасадный лидер")["память"] = \
            "это лицо было НАД процессиями — но что-то в его глазах было не властью, а страхом"
        next(a for a in cast if a["роль"] == "слабое звено")["память"] = \
            "кажется, этот считал монеты культа — и пил, чтобы забыть"
        next(a for a in cast if a["роль"] == "сердце истории")["память"] = \
            "её забрали одной из последних. в этот раз она ещё жива"
        bible = {
            "тема": "цена безопасности — чужая свобода",
            "конфликт": f"культ выкупает {city} у беды, платя людьми",
            "тайна": "исчезновения — «добровольные» жертвы",
            "правда": "фасадный лидер — заложник; истинный глава прячется в тени ремесла",
            "прошлый_цикл": (f"В прошлый раз {city} съела Жатва: игрок понял всё слишком поздно, "
                             "союзники погибли по одному, и город принял тьму как цену покоя."),
            # то, что игрок ЗНАЕТ с пролога — только общее, БЕЗ правды (кто глава — добывать)
            "память_регрессора": [
                "в городе действует культ — исчезновения не случайны",
                "беда идёт по расписанию: примерно раз в несколько дней — новая жертва",
                "стража прогнила ещё до того, как всё началось — ей верить нельзя",
                "в прошлый раз всё вскрылось слишком поздно: копай раньше и глубже",
            ],
            "дельта": ["слабое звено в этот раз уже под подозрением культа — времени меньше"],
            "входы": [
                {"вид": "доска", "суть": "объявление о пропавшем"},
                {"вид": "слух", "суть": "шёпот в таверне о ночных процессиях"},
                {"вид": "улика", "суть": "письмо с двойным дном в лавке"},
                {"вид": "память", "суть": "регрессор помнит: следующая жертва ещё жива"},
                {"вид": "сцена", "суть": "ночью двое волокут мешок к реке"},
            ],
            "акты": [
                {"n": 1, "имя": "Никто", "вопрос": "как заставить город услышать",
                 "реверс": "память подвела: дельта №1"},
                {"n": 2, "имя": "Паутина", "вопрос": "как расколоть иерархию",
                 "реверс": "правда живёт внизу: казначей важнее иерарха"},
                {"n": 3, "имя": "Цена", "вопрос": "чем платить за правду",
                 "реверс": "фасад — заложник; удар по тени"},
            ],
            "каст": cast,
        }
