"""E2 (время, docs/citysim.md §E): ЧАСЫ ЗАВЕДЕНИЙ — единый источник, когда venue открыт.

Канонические окна фронтирного городка по типу заведения (час_открытия, час_закрытия); закрытие
> 24 = за полночь (таверна до 01:00, игорный дом до 04:00). Гейтит доступ ИГРОКА к услугам/
торговле (B2): ночью лавка заперта, рынок работает днём, таверна — вечер-ночь. Тот же канон
питает нарратив («лавка закрыта до утра») и рыночную витрину (open/закрыто-до).

Key functions
-------------
hours_for(info: str) -> tuple[int, int] | None : Query venue hours by name.
is_open(info: str, gt: int) -> bool : Check if venue is open at game time.
opens_at(info: str) -> int | None : Get opening hour for narrative text.
"""

from __future__ import annotations

# по подстроке типа/имени здания → (открытие, закрытие); закрытие>24 ⇒ за полночь
_HOURS: dict[str, tuple[int, int]] = {
    "таверн": (11, 25), "трактир": (11, 25),          # 11:00 – 01:00
    "игорн": (18, 28),                                 # 18:00 – 04:00 (притон ночи)
    "рынок": (7, 17), "рыноч": (7, 17),
    "лавк": (8, 18), "склад": (8, 18), "мастерск": (8, 18), "лавч": (8, 18),
    "кузн": (7, 18), "оружейн": (8, 18), "дубиль": (8, 18), "сапож": (8, 18), "коже": (8, 18),
    "мельниц": (6, 16), "мельн": (6, 16), "пекарн": (6, 15),
    "храм": (6, 21), "молельн": (6, 21), "часовн": (6, 21), "святил": (6, 21),  # службы; вход всегда
    "гильд": (8, 19),
    "лечебн": (7, 20), "знахар": (7, 20), "травниц": (7, 20),
}


def hours_for(info: str) -> tuple[int, int] | None:
    """Часы заведения по строке «тип имя» (первое совпадение подстроки), иначе None (нет часов)."""
    low = (info or "").lower()
    return next((h for k, h in _HOURS.items() if k in low), None)


def is_open(info: str, gt: int) -> bool:
    """Открыто ли заведение в игровое время gt (минуты). Нет часов ⇒ True (жильё/прочее — всегда)."""
    hrs = hours_for(info)
    if hrs is None:
        return True
    h = (gt // 60) % 24
    open_h, close_h = hrs
    if close_h > 24:                                   # окно за полночь: [open,24) ∪ [0,close-24)
        return h >= open_h or h < (close_h - 24)
    return open_h <= h < close_h


def opens_at(info: str) -> int | None:
    """Час открытия (для нарратива «закрыто до 8»), иначе None."""
    hrs = hours_for(info)
    return hrs[0] if hrs else None
